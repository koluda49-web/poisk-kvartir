// Проверка, что скрипт страницы вообще запустится в браузере.
//
// Зачем. Страница собирается на сервере как одна большая строка, и внутри неё
// легко испортить экранирование: например, \n превращается в настоящий перенос
// и рвёт строку пополам. Сайт после этого отдаётся с кодом 200, но у посетителя
// не работает НИЧЕГО. Команда `node -c` такое не ловит — она проверяет только
// сам сервер, а не то, что он отдаёт.
//
// Сервер должен быть уже запущен.
//   npm start                        а в другом окне:
//   npm run проверка-страницы
//   npm run проверка-страницы https://nochy.by

const BASE = process.argv[2] || 'http://127.0.0.1:8080';

// Своим скриптом собирается не только главная: страница места и страница
// маршрута — такие же строки, и экранирование в них рвётся так же легко.
const СТРАНИЦЫ = [
  ['главная',           '/'],
  ['страница места',    '/mesto/244-nesvizhskij-zamok'],
  ['страница маршрута', '/marshrut?p=2416,244'],
  ['подборка',          '/podborka/osen'],
  ['готовый маршрут',   '/m/lida-voronovo'],
  ['маршрут на 2 дня',  '/m/braslavshchina-2-dnya'],
  ['выходные',          '/vyhodnye'],
  ['город',             '/grodno'],
];

// «Похожие на ссылку» куски в коде скриптов (19.10). Роботы читают href="…" и src="…"
// и в тексте скрипта и шли по кускам вроде /mesto/' + p.id + '-' + … и /' + x.link +
// (404 в журнале). Атрибут с подстановкой собирается функцией (атрСсылки, атрСнимка),
// и в тексте скрипта значение href/src не должно содержать кавычек и « + ».
function похожиеНаСсылку(code) {
  const out = [];
  for (const м of code.matchAll(/\b(?:href|src|action)\s*=\s*(["'])/g)) {
    const кв = м[1], от = м.index + м[0].length, до = code.indexOf(кв, от);
    const v = до < 0 ? code.slice(от, от + 80) : code.slice(от, до);
    if (/["']|\s\+\s/.test(v)) out.push(м[0] + v.slice(0, 60));
  }
  return out;
}

let checked = 0, bad = 0;
for (const [имя, путь] of СТРАНИЦЫ) {
  const html = await (await fetch(BASE + путь)).text();
  const re = /<script([^>]*)>([\s\S]*?)<\/script>/g;
  let m, наСтранице = 0;
  while ((m = re.exec(html))) {
    const attrs = m[1] || '', code = m[2];
    if (/\bsrc=/.test(attrs)) continue;                                // подключённый файл, не наш текст
    if (/type=["'](?!text\/javascript|module)/.test(attrs)) continue;  // ld+json и прочее не код
    checked++; наСтранице++;
    try { new Function(code); }
    catch (e) { bad++; console.log('Сломан блок скрипта (' + имя + '): ' + e.message); }
    const куски = похожиеНаСсылку(code);
    if (куски.length) { bad++; console.log('В скрипте (' + имя + ') куски, похожие на ссылку (' + куски.length + '): ' + куски.slice(0, 3).join(' | ')); }
  }
  if (!наСтранице) { bad++; console.log('На странице «' + имя + '» не нашлось ни одного своего блока — проверять нечего?'); }
}

console.log(bad
  ? ('СЛОМАНО блоков: ' + bad + ' — страница у посетителя работать не будет')
  : ('Скрипты страниц разбираются без ошибок (проверено блоков: ' + checked + ')'));
// Выходим через exitCode, а не process.exit: резкий выход не даёт node закрыть
// сетевое соединение и на Windows роняет его с ошибкой libuv.
process.exitCode = bad ? 1 : 0;
