  await new Promise(r => { if (!жив(держатель)) r(); else { держатель.once('exit', r); setTimeout(r, 5000); } });
  check('освободили — папка удаляется', await удалитьПапкуЖдя(папка, { ждать: 10000 }) && !existsSync(папка));
