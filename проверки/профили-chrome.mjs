  const держатель = spawn('powershell', ['-NoProfile', '-NonInteractive', '-Command',
    "$f = [IO.File]::Open('" + join(папка, 'Default', 'x') + "', 'Open', 'Read', 'None'); Write-Output 1; Start-Sleep 180"],
    { stdio: ['ignore', 'pipe', 'ignore'] });
