// Правки точек справочника: имя, описание и свой снимок с Викисклада.
//
// Зачем. У части точек kudin.by короткое имя («Церковь»), нет описания или
// нет ни одного снимка. Мы дополняем их сами: текст — из открытых источников,
// фото — с Викисклада, со свободной лицензией и подписью автора. Проверяем,
// что правка подменяет имя, не затирает описание справочника, когда своего
// текста в ней нет, что снимок из правки становится обложкой в списке мест
// и первым в описании (снимки kudin остаются после него), что на странице
// места появляется подпись с лицензией — и что чужой адрес в pic просто
// не берётся, а точка остаётся живой. Без браузера.
//
// Сервер должен быть запущен с проверочными правками:
//   METRIKA_OFF=1 PORT=8241 PRAVKI_TEST="$(cat проверки/правки-точек.json)" node kvartiry-server.js
//   node проверки/правки-точек.mjs http://127.0.0.1:8241
// Настоящих правок со снимком пока нет, поэтому проверка подкладывает свои
// через PRAVKI_TEST — только pic и подпись, имена точек остаются справочными.
import { readFileSync } from 'node:fs';

const SITE = process.argv[2] || 'http://127.0.0.1:8241';
const ПРОБНЫЕ = JSON.parse(readFileSync(new URL('./правки-точек.json', import.meta.url), 'utf8'));

let failed = 0, passed = 0;
const check = (n, ok, d) => ok ? (passed++, console.log('  OK   ' + n)) : (failed++, console.log('  ПАДАЕТ ' + n + (d ? '  — ' + d : '')));
const json = async p => (await fetch(SITE + p)).json();
const найти = async (q, id) => ((await json('/api/places?q=' + encodeURIComponent(q))).items || []).find(x => x.id === id);

// ── имя и описание: правки, которые уже есть в коде ──────────────────────
console.log('=== имя и описание ===');
for (const [id, имя, запрос, вТексте] of [
  [286,  'Церковь Рождества Богородицы (Мурованка)',   'Мурованка', /храм-крепость/i],
  [4851, 'Костёл Святой Троицы (Ишкольдь)',            'Ишкольд',   /1449/],
  [8179, 'Усадьба Толстых (Грудиновка)',               'Грудиновка', /Толстой/i],
  [4688, 'Костёл Матери Божией Шкаплерной (Идолта)',   'Идолта',    /модерн/i],
]) {
  const т = await найти(запрос, id);
  check(id + ': в списке мест имя из правки', !!т && т.name === имя, т && т.name);
  const д = await json('/api/place?id=' + id);
  check(id + ': в описании то же имя и свой текст', д.name === имя && вТексте.test(д.text || ''),
        д.name + ' | ' + String(д.text || '').slice(0, 70));
}
// 4678 — правка только с именем: описание справочника должно остаться,
// каким было (у этой точки его нет вовсе — значит, и подменять нечего).
const т4678 = await найти('Постав', 4678);
check('4678: имя из правки («Поставы» по-русски)',
      !!т4678 && т4678.name === 'Костёл Святого Антония Падуанского (Поставы)', т4678 && т4678.name);
const д4678 = await json('/api/place?id=4678');
check('4678: правка без text не выдумывает описание',
      д4678.name === 'Костёл Святого Антония Падуанского (Поставы)' && typeof д4678.text === 'string',
      JSON.stringify(д4678).slice(0, 120));
check('4678: обложка своя (ОБЛОЖКИ), правки снимка у неё нет',
      !!т4678 && String(т4678.pic).startsWith('https://kudin.by/'), т4678 && т4678.pic);

// ── снимок из правки ─────────────────────────────────────────────────────
console.log('\n=== снимок с Викисклада (правка ' + Object.keys(ПРОБНЫЕ).join(', ') + ') ===');
const [сФото, чужой, сОбложкой] = [4999, 4694, 4985];
const пр = ПРОБНЫЕ[сФото];
const д4999 = await json('/api/place?id=' + сФото);
check('проверочные правки поданы серверу (PRAVKI_TEST)', (д4999.pics || []).includes(пр.pic),
      'сервер запущен без PRAVKI_TEST — подними его так, как написано в шапке файла');
check(сФото + ': снимок правки идёт первым, снимки kudin — после него',
      (д4999.pics || [])[0] === пр.pic && (д4999.pics || []).slice(1).some(u => /kudin\.by/.test(u)),
      (д4999.pics || []).slice(0, 3).join(' | '));
check(сФото + ': в ответе подпись cred с автором, лицензией и источником',
      !!д4999.cred && д4999.cred.lic === пр.lic && д4999.cred.author === пр.author && д4999.cred.src === пр.src,
      JSON.stringify(д4999.cred));
check(сФото + ': описание справочника на месте (правка без text его не трогает)',
      String(д4999.text || '').length > 100, String(д4999.text || '').slice(0, 60));
const т4999 = await найти('Беница', сФото);
check(сФото + ': в списке мест обложка — снимок из правки', !!т4999 && т4999.pic === пр.pic, т4999 && т4999.pic);
check(сФото + ': имени правка не меняла — оно справочное',
      !!т4999 && т4999.name === 'Костёл Пресвятой Троицы', т4999 && т4999.name);

const стр = await fetch(SITE + '/mesto/' + сФото);
const html = await стр.text();
const кадры = [...html.matchAll(/<img class="hero[^"]*"\s+(?:src|data-src)="([^"]+)"/g)].map(m => m[1]);
check('/mesto/' + сФото + ' — 200, первый кадр наш', стр.status === 200 && кадры[0] === пр.pic,
      стр.status + ' ' + кадры.slice(0, 2).join(' | '));
check('/mesto/' + сФото + ': подпись «Фото с Викисклада» с автором, лицензией и ссылкой на источник',
      html.includes('Фото с Викисклада: ' + пр.author + ', ' + пр.lic) && html.includes('href="' + пр.src + '"'),
      (html.match(/<p class="cred">[\s\S]{0,180}/) || [''])[0]);

// ── чужой адрес в pic ────────────────────────────────────────────────────
console.log('\n=== чужой адрес просто не берётся ===');
const д4694 = await json('/api/place?id=' + чужой);
check(чужой + ': точка жива, снимка с чужого домена нет и подписи нет',
      д4694.id === чужой && !(д4694.pics || []).some(u => /example\.org/.test(u)) && !д4694.cred,
      JSON.stringify({ pics: (д4694.pics || []).slice(0, 2), cred: д4694.cred }));
const т4694 = await найти('Освея', чужой);
check(чужой + ': в списке мест обложка осталась справочной',
      !!т4694 && !/example\.org/.test(String(т4694.pic)) && !!т4694.pic, т4694 && т4694.pic);
const стр4694 = await fetch(SITE + '/mesto/' + чужой);
const html4694 = await стр4694.text();
check('/mesto/' + чужой + ' — 200 и без чужого домена в странице',
      стр4694.status === 200 && !html4694.includes('example.org'), String(стр4694.status));

// ── своя обложка владельца важнее ────────────────────────────────────────
console.log('\n=== ОБЛОЖКИ важнее снимка из правки ===');
const т4985 = await найти('Молодово', сОбложкой);
check(сОбложкой + ': обложка осталась выбранной владельцем (ОБЛОЖКИ), а не из правки',
      !!т4985 && String(т4985.pic).startsWith('https://kudin.by/') && т4985.pic !== ПРОБНЫЕ[сОбложкой].pic,
      т4985 && т4985.pic);
const д4985 = await json('/api/place?id=' + сОбложкой);
check(сОбложкой + ': в самом описании снимок из правки всё же первый',
      (д4985.pics || [])[0] === ПРОБНЫЕ[сОбложкой].pic, (д4985.pics || []).slice(0, 2).join(' | '));

// ── проверка адреса ──────────────────────────────────────────────────────
// Те же правила, что у ссылкаОписания: https, свой хост, без порта и «логина@».
console.log('\n=== какие адреса годятся ===');
const годные = [
  'https://thumb.wikimedia.org/wikipedia/commons/thumb/a/a1/X.jpg/640px-X.jpg',
  'https://upload.wikimedia.org/wikipedia/commons/a/a1/X.jpg',
  'https://commons.wikimedia.org/wiki/File:X.jpg',
];
const негодные = [
  'http://upload.wikimedia.org/wikipedia/commons/a/a1/X.jpg',          // не https
  'https://upload.wikimedia.org:8443/wikipedia/commons/a/a1/X.jpg',    // чужой порт
  'https://kto@upload.wikimedia.org/wikipedia/commons/a/a1/X.jpg',     // «логин@»
  'https://evil.example.org/wikipedia/commons/a/a1/X.jpg',             // чужой домен
  'https://upload.wikimedia.org.evil.example.org/X.jpg',               // домен-двойник
  'https://example.org/upload.wikimedia.org/X.jpg',                    // хост в пути
  'javascript:alert(1)',                                               // вообще не адрес
  '/фото-точек/X.jpg',                                                 // относительный
];
// Берём сам код проверки адреса из сервера, а не переписываем его здесь:
// переписанная копия проверяла бы саму себя.
const код = readFileSync(new URL('../kvartiry-server.js', import.meta.url), 'utf8');
const начало = код.indexOf('const ХОСТЫ_ВИКИСКЛАДА');
// от списка хостов до строки с одинокой «}» — это конец функции
const кусок = начало < 0 ? '' : (код.slice(начало).match(/^[\s\S]*?\r?\n\}\r?\n/) || [''])[0];
check('в сервере нашлась функция снимокВикисклада', /function снимокВикисклада/.test(кусок), кусок.slice(0, 60));
const снимокВикисклада = new Function(кусок + '\nreturn снимокВикисклада;')();
check('годные адреса Викисклада принимаются', годные.every(u => снимокВикисклада(u) === u),
      годные.filter(u => снимокВикисклада(u) !== u).join('; '));
check('негодные отбрасываются (пустая строка, не исключение)',
      негодные.every(u => снимокВикисклада(u) === ''), негодные.filter(u => снимокВикисклада(u) !== '').join('; '));
check('мусор вместо адреса не роняет проверку',
      [null, undefined, 0, {}, [], 'https://upload.wikimedia.org/' + 'x'.repeat(600)]
        .every(u => снимокВикисклада(u) === ''));

console.log('\nПройдено ' + passed + ', падает ' + failed);
process.exit(failed ? 1 : 0);
